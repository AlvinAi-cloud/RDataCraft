check(fails(pc_ai_prepare(tab,s,'Synthetic',plan(op('rename_columns','Duplicate',Control='Treatment A')))),'duplicate column names reject')
r<-pc_ai_prepare(tab,s,'Synthetic',plan(op('transform','Log10',operation='log10')))
check(isTRUE(all.equal(as.numeric(r$table[[1]]),log10(as.numeric(tab[[1]])))),'transform runs locally on a copy')
check(identical(tab,original),'data transforms leave the original table intact')
check(fails(pc_ai_prepare(tab,s,'Synthetic',plan(op('transform','Unsupported transform',operation='eval')))),'arbitrary transforms reject')
