check<-function(ok,label) {if(!isTRUE(ok)) stop('FAIL: ',label,call.=FALSE);checks<<-checks+1L;cat('PASS:',label,'\n')}
fails<-function(expr) inherits(tryCatch(force(expr),error=identity),'error')
op<-function(type,title,...) list(type=type,title=title,parameters=lapply(names(list(...)),function(key) list(key=key,value=as.character(list(...)[[key]]))))
plan<-function(...) list(answer='Synthetic test proposal',operations=list(...))
s<-pc_defaults();tab<-pc_example('column')$table;original<-tab
context<-pc_ai_context(tab,s,'Synthetic',FALSE)
check(is.null(context$data_tsv) && is.null(context$data_check),'unshared context excludes observations and computed results')
check(!is.null(pc_ai_context(tab,s,'Synthetic',TRUE)$data_check),'shared context includes real R results')
