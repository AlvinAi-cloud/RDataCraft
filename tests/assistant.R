check(length(r$layout$selected)==2 && grepl('SD and SEM',r$preview,fixed=TRUE),'two-panel layout is rendered before application')
check(fails(pc_ai_prepare(tab,s,'Synthetic',pc_ai_local_plan('band',sx))),'time-course operations cannot bypass the table contract')
check(fails(pc_ai_local_plan('band',s)),'local band shortcut explains the XY requirement')
check(fails(pc_ai_prepare(tab,s,'Synthetic',plan(op('layout','Invalid layout',columns='4')))),'layout geometry is validated')
