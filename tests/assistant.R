check(grepl('<svg',r$preview,fixed=TRUE),'graph preview is rendered before application')
r<-pc_ai_prepare(tab,s,'Synthetic',pc_ai_local_plan('summary',s))
check(r$reports[[1]]$result$method=='descriptive','analysis reports come from the R analysis engine')
r<-pc_ai_prepare(tab,s,'Synthetic',plan(op('analysis','Welch test',method='welch')))
expected<-pc_analyze(pc_normalize(tab,'column'),'welch',s$group1,s$group2,s)
check(isTRUE(all.equal(r$reports[[1]]$result$p,expected$p)),'assistant does not replace computed P values with generated numbers')
check(fails(pc_ai_prepare(tab,s,'Synthetic',plan(op('graph','Bad graph',graph='unsupported')))),'unsupported graphs reject atomically')
check(fails(pc_ai_prepare(tab,s,'Synthetic',plan(op('analysis','Wrong analysis',method='logrank')))),'analysis must match the table contract')
check(fails(pc_ai_prepare(tab,s,'Synthetic',plan(op('shell','Injected code',command='system(1)')))),'code execution is not an assistant operation')
check(fails(pc_ai_prepare(tab,s,'Synthetic',plan(op('graph','Unknown option',system='anything')))),'unknown settings reject')
check(fails(pc_ai_prepare(tab,s,'Synthetic',plan(op('graph','Bad numeric',font_size='NaN')))),'nonfinite numeric settings reject')
check(fails(pc_ai_prepare(tab,s,'Synthetic',plan(op('graph','Bad logical',show_p='yes')))),'logical settings require exact true/false values')
check(fails(pc_ai_prepare(tab,s,'Synthetic',plan(op('graph','Too large',x_axis_length='350')))),'axis fit validation also protects assistant previews')
r<-pc_ai_prepare(tab,s,'Synthetic',plan(op('rename_columns','Rename',Control='Vehicle')))
