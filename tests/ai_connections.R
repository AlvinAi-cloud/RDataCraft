source('app.R')
checks<-0L
check<-function(ok,label) {if(!isTRUE(ok)) stop('FAIL: ',label);checks<<-checks+1L;cat('PASS:',label,'\n')}
fails<-function(expr) inherits(tryCatch(force(expr),error=identity),'error')
plan<-' "answer": "Synthetic answer", "operations": [] '
plan<-paste0('{',plan,'}')
parsed<-function(value) jsonlite::fromJSON(pc_ai_response_text(value),simplifyVector=FALSE)
check(parsed(list(output=list(list(content=list(list(type='output_text',text=plan))))))$answer=='Synthetic answer','OpenAI and ChatGPT completed responses are parsed')
check(parsed(list(content=list(list(type='text',text=plan))))$answer=='Synthetic answer','Claude responses are parsed')
check(parsed(list(candidates=list(list(finishReason='STOP',content=list(parts=list(list(text=plan)))))))$answer=='Synthetic answer','Gemini responses are parsed')
check(parsed(list(choices=list(list(finish_reason='stop',message=list(content=plan)))))$answer=='Synthetic answer','compatible provider responses are parsed')
check(parsed(list(output_text=paste0('```json\n',plan,'\n```')))$answer=='Synthetic answer','single fenced JSON envelope is accepted')
check(fails(pc_ai_response_text(list(status='incomplete',output_text=plan))),'incomplete responses cannot become operation plans')
check(fails(pc_ai_response_text(list(choices=list(list(finish_reason='length',message=list(content=plan)))))),'truncated compatible responses are rejected')
check(fails(pc_ai_response_text(list(stop_reason='max_tokens',content=list(list(type='text',text=plan))))), 'truncated Claude responses are rejected')
check(fails(pc_ai_response_text(list(output_text='{"answer":"invented"}'))),'missing operation lists are rejected')
check(fails(pc_ai_response_text(list(output_text=paste(rep('x',100001),collapse='')))),'provider response text is bounded')
html<-as.character(pc_ai_connections_ui())
check(all(vapply(c('Continue with ChatGPT','OpenAI API','Claude API','Gemini API','OpenAI-compatible','Test connection','Forget saved API connection'),grepl,logical(1),x=html,fixed=TRUE)),'account dialog covers direct sign-in and all supported providers')
check(grepl('type="password"',html,fixed=TRUE),'API credential entry is masked')
profile<-tempfile('rdatacraft-ai-test-');dir.create(profile)
Sys.setenv(RDATACRAFT_AI_PROFILE=profile)
check(identical(pc_ai_profile(),normalizePath(profile,winslash='/')),'test profiles are isolated from personal accounts')
Sys.unsetenv('RDATACRAFT_AI_PROFILE');unlink(profile,recursive=TRUE)
cat(checks,'checks passed\n')
