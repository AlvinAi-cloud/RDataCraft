checks<-0L
check<-function(ok,label){if(!isTRUE(ok)) stop('FAIL: ',label,call.=FALSE);checks<<-checks+1L;cat('PASS:',label,'\n')}
fails<-function(expr) inherits(tryCatch(force(expr),error=identity),'error')
near<-function(a,b,tol=1e-8) isTRUE(all.equal(unname(a),unname(b),tolerance=tol,check.attributes=FALSE))
s<-pc_defaults();s$layout<-'multiple';s$method<-'pca';s$graph<-'pcascores';s$show_p<-FALSE
empty_column<-pc_normalize(pc_check_table(data.frame(Value=c(1,3,5),Empty=rep(NA_character_,3))),'multiple')
check(nrow(empty_column$data)==3 && pc_summary(empty_column)$n[2]==0,'empty numeric candidate columns do not break inspection of saved result tables')
# Independent R reference and matrix invariants: signs do not affect distances or variance.
tab<-pc_check_table(datasets::USArrests);n<-pc_normalize(tab,'multiple');z<-pc_pca(n,s)
ref<-stats::prcomp(datasets::USArrests,center=TRUE,scale.=TRUE)
check(near(z$scree$eigenvalue,ref$sdev^2),'scaled PCA eigenvalues agree with stats::prcomp on USArrests')
check(near(z$scree$variance_percent,100*ref$sdev^2/sum(ref$sdev^2)),'explained variance agrees with an independent prcomp reference')
check(near(tail(z$scree$cumulative_percent,1),100),'all components account for 100 percent of variance')
check(near(as.matrix(dist(z$scores[,paste0('PC',1:4)])),as.matrix(dist(ref$x))),'PCA scores preserve reference observation distances independent of SVD signs')
check(near(crossprod(as.matrix(z$loadings[,-1])),diag(4)),'eigenvector loading columns are orthonormal')
reconstructed<-as.matrix(z$scores[,paste0('PC',1:4)])%*%t(as.matrix(z$loadings[,-1]))
check(near(reconstructed,scale(datasets::USArrests)),'all scores and loadings reconstruct the standardized observations')
check(near(diag(stats::cov(z$scores[,paste0('PC',1:4)])),z$scree$eigenvalue),'score variances equal PCA eigenvalues')
u<-pc_pca(n,modifyList(s,list(pca_scale=FALSE)))
ru<-stats::prcomp(datasets::USArrests,center=TRUE,scale.=FALSE)
check(near(u$scree$eigenvalue,ru$sdev^2),'unscaled centered PCA agrees with covariance PCA reference')
check(!near(u$scree$variance_percent,z$scree$variance_percent),'scaling choice changes the fit when variable units differ')
e<-pc_example('multiple');t<-e$table;ne<-pc_normalize(t,'multiple');s$pca_group_column<-'Group';s$pca_label_column<-'Sample'
a<-pc_analyze(ne,'pca',options=s)
check(nrow(a$pca$scores)==12 && nrow(a$pca$loadings)==4 && length(unique(a$pca$scores$group))==3,'text metadata are excluded from variables and retained in scores')
check(is.na(a$p) && grepl('unsupervised',paste(a$notes,collapse=' ')),'PCA does not invent a group-significance P value')
t2<-t;t2$Group<-rev(t2$Group)
z2<-pc_pca(pc_normalize(t2,'multiple'),s)
check(near(z2$scores[,paste0('PC',1:4)],a$pca$scores[,paste0('PC',1:4)]),'group colors do not enter the PCA fit')
selected<-modifyList(s,list(pca_variables='["Signal","Marker","Response"]'))
check(length(pc_pca(ne,selected)$variables)==3,'explicit numeric variable selection controls the fit')
t3<-t;t3$NumericID<-1:12
z3<-pc_pca(pc_normalize(t3,'multiple'),modifyList(s,list(pca_label_column='NumericID')))
check(!'NumericID' %in% z3$variables && identical(z3$scores$sample,as.character(1:12)),'numeric sample IDs can explicitly serve as metadata')
missing<-t;missing$Signal[2]<-NA
check(fails(pc_pca(pc_normalize(missing,'multiple'),s)),'missing data stop PCA by default')
zmiss<-pc_pca(pc_normalize(missing,'multiple'),modifyList(s,list(pca_missing='complete')))
check(identical(zmiss$excluded,2L) && !2 %in% zmiss$scores$row && nrow(zmiss$scores)==11,'complete-row exclusion preserves source row identities')
check(grepl('No missing values were imputed',paste(zmiss$notes,collapse=' '),fixed=TRUE),'missing-row policy is documented without imputation')
bad<-t;bad$Signal[2]<-'oops'
check(fails(pc_pca(pc_normalize(bad,'multiple'),s)),'mixed text in a numeric candidate cannot silently remove that variable')
bad<-t;bad$Signal[2]<-'Inf'
check(fails(pc_pca(pc_normalize(bad,'multiple'),s)),'nonfinite input values reject')
bad<-t;bad$Marker<-4
check(fails(pc_pca(pc_normalize(bad,'multiple'),s)),'constant variables reject before SVD')
check(fails(pc_pca(pc_normalize(t[1:2,],'multiple'),s)),'PCA requires at least three complete observations')
check(fails(pc_pca(ne,modifyList(s,list(pca_variables='["Signal"]')))),'PCA requires at least two variables')
check(fails(pc_pca(ne,modifyList(s,list(pca_variables='["Signal","Missing"]')))),'unknown selected variables reject')
check(fails(pc_pca(ne,modifyList(s,list(pca_variables='["Signal","Signal"]')))),'duplicate variable selection rejects')
check(fails(pc_pca(ne,modifyList(s,list(pca_missing='impute')))),'unsupported missing-value policies reject')
check(fails(pc_pca(ne,modifyList(s,list(pca_x=1.5)))),'fractional component indices reject')
check(fails(pc_pca(ne,modifyList(s,list(log_y=TRUE)))),'log axes cannot misrepresent signed PCA coordinates')
