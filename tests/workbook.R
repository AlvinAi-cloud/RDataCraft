app <- source("app.R")$value
checks <- 0L
check <- function(ok,label) {if(!isTRUE(ok)) stop("FAIL: ",label,call.=FALSE);checks<<-checks+1L;cat("PASS:",label,"\n")}
shiny::testServer(app, {
  # Explicit fixture: production startup is intentionally empty.
  raw(pc_example("column")$table);sheet_name("Treatment groups");project_name("Example study");document_open(TRUE)
 do.call(session$setInputs, pc_defaults());session$flushReact()
 original <- raw();origsettings <- settings()
 for(layout in c("grouped","contingency","survival")) {
  e<-pc_example(layout)
  session$setInputs(worksheet_layout=layout,worksheet_name=paste("Example",layout),worksheet_example=TRUE,confirm_worksheet=match(layout,c("grouped","contingency","survival")))
  session$flushReact();ss<-pending()
  do.call(session$setInputs,ss);session$flushReact()
  check(normalized()$layout==layout,paste(layout,"worksheet template activates its table contract"))
  check(is.null(analysis_state()$error),paste(layout,"template runs its default analysis"))
  check(settings()$graph %in% unname(pc_graphs(layout)),paste(layout,"template chooses compatible graphs"))
 }
 check(length(workbook())==4,"mixed-format worksheets coexist in one workbook")
 session$setInputs(worksheet="D1");session$flushReact();do.call(session$setInputs,if(is.null(pending())) sheets()[[active_sheet()]]$settings else pending());session$flushReact()
 check(identical(raw(),original),"switching back restores original source observations")
 check(settings()$method==origsettings$method,"switching back restores analysis options")
 session$setInputs(transform_kind="percent_control",transform_control="Control",apply_transform=1);session$flushReact();do.call(session$setInputs,if(is.null(pending())) sheets()[[active_sheet()]]$settings else pending());session$flushReact()
 check(active_sheet()=="D5" && length(workbook())==5,"normalization creates a distinct worksheet")
 check(abs(mean(as.numeric(raw()$Control))-100)<1e-9,"normalized control has mean 100 percent")
 check(identical(pc_read_text(workbook()$D1$data_tsv,"\t"),original),"normalization preserves the source worksheet")
 session$setInputs(rename_sheet="Normalized study",confirm_rename_sheet=1);session$flushReact()
 check(workbook()$D5$name=="Normalized study","worksheet rename persists in workbook snapshot")
 jsonlite::write_json(snapshot(),"artifacts/expanded/reactive-workbook.rdatacraft",auto_unbox=TRUE,pretty=TRUE,na="null",digits=15)
 saved<-pc_load_project("artifacts/expanded/reactive-workbook.rdatacraft")
 check(length(saved$worksheets)==5 && saved$active=="D5","reactive save produces a complete portable workbook")
 session$setInputs(desktop_saved=list(path=normalizePath("artifacts/expanded/reactive-workbook.rdatacraft"),nonce=1));session$flushReact()
 check(identical(signature(),saved_signature()),"saving a multi-worksheet project clears edited state")
 session$setInputs(data_grid_cell_edit=list(row=1,col=1,value="101"));session$flushReact()
 check(!identical(signature(),saved_signature()),"editing active observations marks the workbook unsaved")
 session$setInputs(desktop_open_project=list(path=normalizePath("artifacts/expanded/reactive-workbook.rdatacraft"),nonce=2));session$flushReact();do.call(session$setInputs,if(is.null(pending())) sheets()[[active_sheet()]]$settings else pending());session$flushReact()
 check(identical(signature(),saved_signature()),"opening a saved multi-worksheet project restores clean state")
 session$setInputs(worksheet="D4");session$flushReact();do.call(session$setInputs,if(is.null(pending())) sheets()[[active_sheet()]]$settings else pending());session$flushReact()
 check(normalized()$layout=="survival" && !is.null(analysis_state()$value$survival_fit),"inactive survival analysis restores after workbook reopen")
 # A blank survival row can be entered one cell at a time; partial subjects never reach analysis.
 apply_sheet(pc_blank("survival"), sheets()[[active_sheet()]]$settings)
 session$flushReact()
 session$setInputs(data_grid_cell_edit=list(row=1,col=0,value="5"));session$flushReact()
 check(raw()[1,1]=="5","survival editor retains a partial subject while entering cells")
 check(inherits(tryCatch(normalized(),error=identity),"error"),"partial survival subjects block analysis instead of silently disappearing")
 jsonlite::write_json(snapshot(),"artifacts/expanded/partial-survival.rdatacraft",auto_unbox=TRUE,na="null",digits=15)
 check(pc_load_project("artifacts/expanded/partial-survival.rdatacraft")$table[1,1]=="5","unfinished survival observations can be saved and reopened")
 session$setInputs(data_grid_cell_edit=list(row=1,col=1,value="1"));session$flushReact()
 session$setInputs(data_grid_cell_edit=list(row=1,col=2,value="New subject group"));session$flushReact()
 check(nrow(normalized()$data)==1,"completed survival subject becomes available to analysis")
 session$setInputs(desktop_action=list(name="new",nonce=3));session$flushReact();do.call(session$setInputs,if(is.null(pending())) sheets()[[active_sheet()]]$settings else pending());session$flushReact()
 check(length(workbook())==1 && all(is.na(raw())),"New project resets the workbook without carrying old worksheets")
})
cat("\n",checks," workbook workflow checks passed.\n",sep="")
