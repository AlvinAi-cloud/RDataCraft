# Exercise reactive workflows without a browser or network listener.
app <- source("app.R")$value
checks <- 0L
check <- function(value, label) {
  if (!isTRUE(value)) stop("FAIL: ", label, call. = FALSE)
  checks <<- checks + 1L
  cat("PASS:", label, "\n")
}
shiny::testServer(app, {
  # Explicit fixture: production startup is intentionally empty.
  raw(pc_example("column")$table);sheet_name("Treatment groups");project_name("Example study");document_open(TRUE)
  do.call(session$setInputs, pc_defaults())
  session$flushReact()
  check(nrow(normalized()$data) == 24, "explicitly loaded session fixture has example data")
  check(is.finite(analysis_state()$value$p), "initial session analysis is available")
  session$setInputs(data_grid_cell_edit = list(row = 1, col = 0, value = "8.9"))
  session$flushReact()
  check(raw()[1, 1] == "8.9", "editing the grid updates the source table")
  session$setInputs(paste_data = "A\tB\n1\t2\n3\t5\n6\t9", apply_paste = 1)
  session$setInputs(group1 = "A", group2 = "B")
  session$flushReact()
  check(identical(names(raw()), c("A", "B")), "pasting a table updates columns")
  check(is.finite(analysis_state()$value$p), "analysis updates after pasted data")
  previous <- raw()
  session$setInputs(paste_data = "A,B\n1,not-a-number", apply_paste = 2)
  session$flushReact()
  check(identical(raw(), previous), "invalid pasted data leaves the previous table intact")
  session$setInputs(import_data = list(name = "treatment.csv", datapath = normalizePath("examples/treatment.csv")))
  session$setInputs(group1 = "Control", group2 = "Treatment A")
  session$flushReact()
  check(nrow(raw()) == 8 && ncol(raw()) == 3, "CSV file upload workflow")
  session$setInputs(import_data = list(name = "observations.xlsx", datapath = normalizePath("tests/fixtures/observations.xlsx")))
  session$setInputs(group1 = "Control", group2 = "Treatment")
  session$flushReact()
  check(nrow(raw()) == 3 && raw()[3, "Treatment"] == "9", "Excel file upload preserves numeric observations")
  session$setInputs(import_data = list(name = "treatment.csv", datapath = normalizePath("examples/treatment.csv")))
  session$setInputs(group1 = "Control", group2 = "Treatment A")
  session$flushReact()
  session$setInputs(method = "anova")
  session$flushReact()
  check(nrow(analysis_state()$value$comparisons) == 3, "ANOVA workflow updates comparisons")
  session$setInputs(nav_analysis = 1)
  session$flushReact()
  check(page() == "analysis", "navigation selects the analysis page")
  session$setInputs(sample_xy = 1)
  session$setInputs(layout = "xy", method = "linear", graph = "scatter", group1 = "Condition A", group2 = "Condition B")
  session$flushReact()
  check(normalized()$layout == "xy", "XY example switches the analysis data layout")
  check(inherits(analysis_state()$value$model, "lm"), "regression workflow produces a fitted model")
  p <- pc_project(raw(), settings())
  jsonlite::write_json(p, "artifacts/tests/xy-project.json", auto_unbox = TRUE)
  session$setInputs(open_project = list(name = "xy.rdatacraft.json", datapath = normalizePath("artifacts/tests/xy-project.json")))
  session$flushReact()
  check(nrow(raw()) == 8 && names(raw())[1] == "Time (hours)", "saved project upload restores the data")
  session$setInputs(open_project = list(name = "column.rdatacraft.json", datapath = normalizePath("artifacts/tests/project.json")))
  session$flushReact()
  check(!is.null(pending()), "cross-layout project waits for layout to update before restoring choices")
  session$setInputs(layout = "column")
  session$flushReact()
  check(is.null(pending()), "project choices restore after the layout changes")
  session$setInputs(method = "welch", group1 = "Control", group2 = "Treatment A", graph = "points")
  session$flushReact()
  check(is.finite(analysis_state()$value$p), "restored column project has a valid comparison")
  session$setInputs(desktop_import_data = list(path = normalizePath("tests/fixtures/observations.xlsx"), nonce = 1))
  session$flushReact()
  check(nrow(raw()) == 3 && raw()[3, "Treatment"] == "9", "native import uses the selected local file")
  session$setInputs(desktop_action = list(name = "new", nonce = 2))
  session$setInputs(layout = "column", method = "descriptive", graph = "points", group1 = "Control", group2 = "Treatment", title = "Untitled figure")
  session$flushReact()
  check(all(is.na(raw())) && nrow(raw()) == 6, "native New creates a blank six-row table")
  check(page() == "data" && project_name() == "Untitled study", "new projects start at the data table")
  session$setInputs(add_row = 1)
  session$flushReact()
  check(nrow(raw()) == 7, "adding a row preserves empty observations")
  session$setInputs(new_group_name = "Drug", confirm_add_group = 1)
  session$flushReact()
  check(identical(names(raw()), c("Control", "Treatment", "Drug")), "adding a column preserves group labels")
  session$setInputs(desktop_open_project = list(path = normalizePath("artifacts/tests/project.json"), nonce = 3))
  session$setInputs(method = "welch", group1 = "Control", group2 = "Treatment A", title = "Treatment response")
  session$flushReact()
  check(nrow(raw()) == 8 && ncol(raw()) == 3, "native Open restores the project table")
  session$setInputs(title = "Changed figure")
  session$flushReact()
  check(!identical(signature(), saved_signature()), "figure edits mark a project unsaved")
  jsonlite::write_json(pc_project(raw(), settings()), "artifacts/tests/native-save.rdatacraft", auto_unbox = TRUE, na = "null")
  session$setInputs(desktop_saved = list(path = normalizePath("artifacts/tests/native-save.rdatacraft"), nonce = 4))
  session$flushReact()
  check(identical(signature(), saved_signature()), "native Save acknowledges the actual saved state")
  session$setInputs(title = "Another edit")
  session$setInputs(desktop_saved = list(path = normalizePath("artifacts/tests/native-save.rdatacraft"), nonce = 5))
  session$flushReact()
  check(!identical(signature(), saved_signature()), "edits made after a save snapshot remain unsaved")
})
cat("\n", checks, " reactive workflow checks passed.\n", sep = "")
