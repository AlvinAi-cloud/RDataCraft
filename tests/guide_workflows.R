# Guide-inspired workflow regressions, independent of Prism's implementation.
app <- source("app.R")$value
checks <- 0L
check <- function(ok, label) {if (!isTRUE(ok)) stop("FAIL: ", label, call. = FALSE); checks <<- checks + 1L; cat("PASS:", label, "\n")}
shiny::testServer(app, {
  # Explicit fixture: production startup is intentionally empty.
  raw(pc_example("column")$table);sheet_name("Treatment groups");project_name("Example study");document_open(TRUE)
  do.call(session$setInputs, pc_defaults()); session$flushReact()
  ack <- function() {target <- isolate(restoring_settings()); if (!is.null(target)) do.call(session$setInputs, target); session$flushReact()}
  before <- raw(); sig <- signature()
  session$setInputs(data_grid_cell_edit = list(row = 1, col = 0, value = "100")); session$flushReact()
  check(raw()[1,1] == "100" && length(data_history()$D1$undo) == 1, "cell commit creates one data undo entry")
  session$setInputs(undo_data = 1); session$flushReact()
  check(identical(raw(), before) && identical(signature(), sig), "undo restores data and original saved signature")
  session$setInputs(redo_data = 1); session$flushReact()
  check(raw()[1,1] == "100", "redo reapplies the committed data edit")
  session$setInputs(undo_data = 2); session$flushReact()
  session$setInputs(data_grid_cell_edit = list(row = 1, col = 0, value = "not numeric")); session$flushReact()
  check(identical(raw(), before) && length(data_history()$D1$redo) == 1, "rejected edits preserve both data and redo history")
  session$setInputs(add_row = 1); session$flushReact()
  check(nrow(raw()) == nrow(before)+1 && !length(data_history()$D1$redo), "a new action clears the abandoned redo branch")
  session$setInputs(undo_data = 3); session$flushReact()
  check(identical(raw(), before), "undo removes a newly added row")
  session$setInputs(paste_data = "A\tB\n1\t3\n2\t5", apply_paste = 1); session$flushReact()
  check(nrow(raw()) == 2 && names(raw())[1] == "A", "replacement paste commits the new table")
  session$setInputs(undo_data = 4); session$flushReact()
  check(identical(raw(), before), "undo recovers data overwritten by paste")
  session$setInputs(new_view_name = "Distribution", confirm_new_view = 1); session$flushReact()
  session$setInputs(graph = "box", method = "descriptive", palette = "monochrome", font_size = 18, grid_lines = TRUE); session$flushReact()
  original <- workbook()$D1
  session$setInputs(duplicate_sheet_name = "Independent repeat", confirm_duplicate_sheet = 1); session$flushReact(); ack()
  check(length(workbook()) == 2 && active_sheet() == "D2", "duplicate creates and selects a new worksheet")
  check(length(view_book()) == 2 && active_view() == "V2", "duplicate preserves all linked views and active selection")
  check(identical(workbook()$D2$views, original$views), "duplicate preserves independent per-view settings")
  session$setInputs(data_grid_cell_edit = list(row = 1, col = 0, value = "55")); session$flushReact()
  check(workbook()$D1$data_tsv == original$data_tsv && raw()[1,1] == "55", "editing duplicated observations leaves the original unchanged")
  session$setInputs(undo_data = 5); session$flushReact()
  check(raw()[1,1] == before[1,1], "undo is scoped to the active duplicated table")
  session$setInputs(navigate_sheet = list(table = "D1", view = "V1", page = "figure", nonce = 1)); session$flushReact(); ack()
  check(active_sheet() == "D1" && active_view() == "V1" && page() == "figure" && settings()$graph == "points", "navigator opens an inactive table's exact graph view")
  session$setInputs(navigate_sheet = list(table = "D2", view = "V2", page = "analysis", nonce = 2)); session$flushReact(); ack()
  check(active_sheet() == "D2" && active_view() == "V2" && page() == "analysis" && settings()$graph == "box", "navigator switches table, view, and destination atomically")
  target <- workbook()$D1$views$V1$settings
  session$setInputs(format_source = "D2:V2", format_targets = "D1:V1", format_size = FALSE, confirm_format = 1); session$flushReact(); ack()
  changed <- workbook()$D1$views$V1$settings
  check(changed$palette == "monochrome" && changed$font_size == 18 && changed$grid_lines, "formatting copies appearance across data tables")
  protected <- setdiff(names(target), c("palette","font_size","point_size","legend_position","grid_lines","show_points"))
  check(identical(changed[protected], target[protected]), "formatting preserves target analysis, graph type, labels, axes, and error definition")
  session$setInputs(navigate_sheet = list(table = "D1", view = "V1", page = "figure", nonce = 3)); session$flushReact(); ack()
  check(settings()$palette == "monochrome" && settings()$method == target$method, "copied style restores when navigating to its target")
  session$setInputs(format_source = "D2:V2", format_targets = "D1:V1", confirm_format = 2); session$flushReact(); ack()
  check(identical(workbook()$D1$settings, workbook()$D1$views$V1$settings), "formatting the active view keeps worksheet settings synchronized")
  unchanged <- workbook()
  session$setInputs(format_targets = c("D1:V1", "missing"), confirm_format = 3); session$flushReact()
  check(identical(workbook(), unchanged), "an invalid formatting target causes no partial changes")
  pc_write_project(snapshot(), "artifacts/tests/guide-workflow.rdatacraft")
  p <- pc_load_project("artifacts/tests/guide-workflow.rdatacraft")
  check(length(p$worksheets) == 2 && p$worksheets$D1$views$V1$settings$font_size == 18, "duplicate families and copied formatting survive save and reopen")
  check(length(pc_navigator_filter(workbook(), "independent")) == 1, "navigator finds a table by its name")
  check(length(pc_navigator_filter(workbook(), "distribution")$D1$views) == 1, "navigator filters named linked views")
  check(!length(pc_navigator_filter(workbook(), "[not a regex]")), "search treats special characters as literal text")
  markup <- as.character(pc_project_navigator(workbook(), "D1", "V1", "figure", ""))
  check(grepl('data-sheet="D1"', markup, fixed = TRUE) && grepl('aria-current="page"', markup, fixed = TRUE), "navigator exposes accessible destination and selected sheet markup")
  check(grepl("Grouped", as.character(pc_template_preview("grouped", FALSE))), "template chooser provides the grouped data contract")
  session$setInputs(worksheet_layout = "contingency", worksheet_name = "Counts", worksheet_example = TRUE, confirm_worksheet = 1); session$flushReact(); ack()
  session$setInputs(add_row = 2); session$flushReact()
  check(is.null(analysis_state()$error) || normalized()$layout == "contingency", "adding a count row preserves a valid count-table contract")
  check(!anyNA(raw()) && all(as.numeric(unlist(tail(raw(), 1)[1,-1], use.names = FALSE)) == 0), "new category rows are labeled and initialized to explicit zero counts")
  session$setInputs(new_group_name = "New population", confirm_add_group = 1); session$flushReact()
  check(all(raw()[["New population"]] == "0"), "new count columns contain explicit zeros")
  session$setInputs(worksheet_layout = "survival", worksheet_name = "Subjects", worksheet_example = TRUE, confirm_worksheet = 2); session$flushReact(); ack()
  sh <- raw()
  session$setInputs(new_group_name = "Extra", confirm_add_group = 2); session$flushReact()
  check(identical(raw(), sh) && ncol(raw()) == 3, "fixed survival table contract prevents a fourth column")
  session$setInputs(desktop_open_project = list(path = normalizePath("artifacts/tests/guide-workflow.rdatacraft"), nonce = 4)); session$flushReact(); ack()
  check(!length(data_history()), "opening a project clears session-only undo histories")
})
h <- pc_history()
for (i in 1:40) h <- pc_history_record(h, paste0('"A"\n', i), paste("edit", i), "column")
check(length(h$undo) == 30, "undo history has a bounded number of states")
check(inherits(try(pc_history_step(h, '"A"\n99', "undo", "xy"), silent=TRUE), "try-error"), "history cannot restore another data layout")
cat(checks, " guide-inspired workflow checks passed.\n")
