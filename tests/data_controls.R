checks <- 0L
check <- function(ok, label) {if (!isTRUE(ok)) stop("FAIL: ", label, call. = FALSE); checks <<- checks + 1L; cat("PASS:", label, "\n")}
errors <- function(expr) inherits(tryCatch(force(expr), error = identity), "error")
tab <- pc_check_table(data.frame(X = c(0,1,2), Control = c(2,4,6), Drug = c(3,6,9)))
replicates <- pc_xy_replicates(tab, 3)
check(ncol(replicates) == 7 && all(is.na(replicates[[3]])), "replicate setup creates three subcolumns per Y series with blank new cells")
check(identical(replicates[[2]], tab[[2]]) && identical(replicates[[5]], tab[[3]]), "replicate setup preserves each series' original observations")
spec <- pc_xy_structure(replicates)
check(identical(spec$groups, c("Control","Drug")) && spec$n == 3, "replicate headers identify two series rather than six independent series")
replicates[[3]] <- c("4","6","8"); replicates[[6]] <- c("5","8","11")
n <- pc_normalize(replicates, "xy")
check(nrow(n$data) == 12 && identical(n$groups, c("Control","Drug")), "normalization combines each series' observed replicates")
check(sum(n$data$group == "Control" & n$data$x == 1) == 2 && n$missing == 6, "normalization retains X alignment and excludes missing replicate cells")
s <- pc_defaults(); s$layout <- "xy"; s$graph <- "xymean"; s$method <- "linear"; s$group1 <- "Control"
a <- pc_analyze(n, "linear", "Control", "Drug", s)
check(abs(unname(coef(a$model)["x"]) - 2) < 1e-10 && a$n == 6, "linear regression fits all observed replicates in the selected series")
p <- pc_plot(n, s, a); z <- p$data
observed_layers <- Filter(function(layer) inherits(layer$geom,"GeomPoint") && is.data.frame(layer$data) && all(c("replicate","row_id","value") %in% names(layer$data)), p$layers)
check(length(observed_layers) == 1 && identical(observed_layers[[1]]$data,n$data), "mean/error graph can overlay each observed replicate alongside fitted curves")
s$show_points <- FALSE
check(length(pc_plot(n,s,a)$layers) == length(p$layers)-1L, "individual replicate overlay follows the appearance control")
s$show_points <- TRUE
check(abs(z$mean[z$group == "Control" & z$x == 0] - 3) < 1e-10, "XY mean graph averages replicate subcolumns at each X")
check(abs(z$sem[z$group == "Control" & z$x == 0] - 1) < 1e-10, "XY SEM uses observed replicate count rather than configured blank slots")
s$error <- "sd"; z <- pc_plot(n, s, a)$data
check(abs(z$margin[z$group == "Control" & z$x == 0] - sqrt(2)) < 1e-10, "XY SD reflects replicate variation")
s$error <- "ci"; z <- pc_plot(n, s, a)$data
check(abs(z$margin[z$group == "Control" & z$x == 0] - qt(0.975,1)) < 1e-10, "XY confidence intervals use the observed degrees of freedom")
check(errors(pc_xy_replicates(replicates, 1)), "reducing replicate count cannot silently discard observations")
two <- pc_xy_replicates(replicates, 2)
check(ncol(two) == 5 && isTRUE(all.equal(pc_normalize(two,"xy")$data, n$data, check.attributes=FALSE)), "empty replicate columns can be removed without changing observations")
check(errors(pc_xy_replicates(tab, 25)) && errors(pc_xy_replicates(tab, 1.5)), "replicate choices enforce whole numbers and total-column limit")
bad <- replicates; names(bad)[3] <- "Unrelated"
check(errors(pc_normalize(bad,"xy")), "mixed replicate and ordinary headers cannot silently split a series")
bad <- replicates; names(bad)[3] <- "Control [rep 9]"
check(errors(pc_normalize(bad,"xy")), "replicate order is validated")
check(identical(pc_xy_replicates(pc_xy_replicates(tab,3),1),tab), "empty replicate expansion reverses to its original table")
pasted <- pc_paste_cells(pc_xy_replicates(tab,2), "0\t2\t4\t3\t5\n1\t4\t6\t6\t8", 1, 1, "xy")
check(pc_normalize(pasted,"xy")$replicates == 2 && pasted[2,5] == "8", "direct paste fills side-by-side Y replicate columns")
expanded <- pc_paste_cells(pc_xy_replicates(tab,2), "1\t2\t3", 1, 4, "xy")
check(ncol(expanded) == 7 && pc_xy_structure(expanded)$n == 2 && is.na(expanded[1,7]), "paste expands replicated XY data by complete series blocks")
markup <- as.character(pc_xy_grid_header(pc_xy_replicates(tab,3)))
check(grepl('colspan="3"', markup, fixed=TRUE) && grepl('Rep 3', markup, fixed=TRUE), "grid groups subcolumns under their Y series names")
check(abs(pc_defaults()$width/25.4 - 3) < 1e-10 && abs(pc_defaults()$height/25.4 - 3) < 1e-10, "new figures default to a three-inch square canvas")
shiny::testServer(app, {
  # Explicit fixture: production startup is intentionally empty.
  raw(pc_example("column")$table);sheet_name("Treatment groups");project_name("Example study");document_open(TRUE)
  do.call(session$setInputs, pc_defaults()); session$flushReact()
  check(grepl("<table", jsonlite::fromJSON(output$data_grid)$x$container, fixed=TRUE), "ordinary data grids always include a valid HTML table container")
  ack <- function() {target <- isolate(restoring_settings()); if (!is.null(target)) do.call(session$setInputs,target); session$flushReact()}
  before <- raw(); sig <- signature()
  session$setInputs(rename_table = list(table="D1",name="  New data table  ",nonce=1)); session$flushReact()
  check(sheet_name() == "New data table" && workbook()$D1$name == "New data table", "inline table rename trims and updates the active table")
  check(!identical(signature(),sig) && identical(raw(),before), "table rename marks document changed while preserving observations")
  session$setInputs(rename_table = list(table="D1",name=" ",nonce=2)); session$flushReact()
  check(sheet_name() == "New data table", "blank table names are rejected without losing the old name")
  session$setInputs(worksheet_layout="xy",worksheet_name="Replicated time course",worksheet_example=FALSE,worksheet_xy_replicates=3,confirm_worksheet=1); session$flushReact(); ack()
  check(active_sheet() == "D2" && ncol(raw()) == 7 && normalized()$replicates == 3 && settings()$graph == "xymean", "new XY table supports a chosen replicate count and mean/error graph")
  check(grepl('colspan="3"', jsonlite::fromJSON(output$data_grid)$x$container, fixed=TRUE), "replicated XY grids render their grouped HTML header")
  session$setInputs(rename_table=list(table="D1",name="Source experiment",nonce=3)); session$flushReact()
  check(workbook()$D1$name == "Source experiment" && active_sheet() == "D2", "renaming an inactive navigator table preserves active selection")
  session$setInputs(grid_paste=c(grid_identity(),list(text="0\t2\t3\t4\t5\t6\t7\n1\t3\t4\t5\t7\t8\t9\n2\t4\t5\t6\t9\t10\t11",row=1,column=1,headers=FALSE,nonce=1))); session$flushReact()
  check(length(normalized()$groups) == 2 && nrow(normalized()$data) == 18, "pasted Y replicates retain two analyzed series")
  old <- raw(); session$setInputs(xy_replicates=1,confirm_xy_replicates=1); session$flushReact()
  check(identical(raw(),old), "replicate setup server rejects removal of populated subcolumns")
  session$setInputs(xy_replicates=4,confirm_xy_replicates=2); session$flushReact()
  check(ncol(raw()) == 9 && normalized()$replicates == 4, "existing XY tables can add replicate slots")
  session$setInputs(undo_data=1); session$flushReact()
  check(identical(raw(),old) && normalized()$replicates == 3, "replicate structure changes are undoable with observations")
  session$setInputs(new_group_name="Additional series",confirm_add_group=1); session$flushReact()
  check(ncol(raw()) == 10 && tail(normalized()$groups,1) == "Additional series", "adding a Y series adds its entire replicate block")
  session$setInputs(width=5*25.4,height=3*25.4); session$flushReact()
  file <- "artifacts/tests/data-controls.rdatacraft"; pc_write_project(snapshot(),file)
  saved <- pc_load_project(file)
  check(jsonlite::read_json(file)$schema_version == 4L, "replicate projects use a schema older apps reject rather than misinterpret")
  nn <- pc_normalize(saved$table,"xy")
  check(saved$worksheets$D1$name == "Source experiment" && saved$worksheets$D2$name == "Replicated time course", "inline table names persist for active and inactive worksheets")
  check(nn$replicates == 3 && length(nn$groups) == 3 && saved$settings$width == 127 && abs(saved$settings$height - 76.2) < 1e-10, "replicate grouping and exact inch dimensions survive project round trip")
  session$setInputs(width=25.4,height=25.4); session$flushReact()
  pc_write_project(snapshot(),file)
  check(pc_load_project(file)$settings$width == 25.4, "small inch canvases remain valid when saved and reopened")
})
shiny::testServer(app, {
  before<-pc_check_table(data.frame(Control=c(3,5,7,8,10),Drug=c(5,9,10,12,15)))
  raw(before);document_open(TRUE)
  s<-pc_defaults();s$method<-"paired";s$group1<-"Drug";s$group2<-"Control";s$series_styles<-'{"Control":{"color":"#123456"},"Drug":{"color":"#654321"}}'
  do.call(session$setInputs,s);session$flushReact()
  other<-s;other$group1<-"Control";other$group2<-"Drug"
  views(list(V1=pc_view(s),V2=pc_view(other,"Reverse comparison")));session$flushReact()
  baseline<-analysis_state()$value$p
  ack<-function(){target<-isolate(restoring_settings());if(!is.null(target)) do.call(session$setInputs,target);session$flushReact()}
  identity<-grid_identity();session$setInputs(rename_column=c(identity,list(column=1,name="Vehicle")));session$flushReact();ack()
  check(settings()$group1=="Drug" && settings()$group2=="Vehicle", "header rename preserves the active paired comparison in its original direction")
  check(view_book()$V2$settings$group1=="Vehicle" && view_book()$V2$settings$group2=="Drug", "header rename updates comparison references in inactive linked views")
  check(is.null(analysis_state()$error) && identical(analysis_state()$value$p,baseline), "renaming a group leaves the recalculated paired-test P value unchanged")
  check(pc_series_styles(settings()$series_styles)$Vehicle$color=="#123456", "renamed series retain their custom graph appearance")
  session$setInputs(undo_data=1);session$flushReact();ack()
  check(settings()$group2=="Control" && view_book()$V2$settings$group1=="Control", "Undo restores header references across linked analyses")
  session$setInputs(redo_data=1);session$flushReact();ack()
  check(settings()$group2=="Vehicle" && identical(analysis_state()$value$p,baseline), "Redo reapplies header references without changing the result")
  loaded<-pc_decode_project(snapshot())
  check(loaded$worksheets$D1$views$V2$settings$group1=="Vehicle" && loaded$settings$group2=="Vehicle", "renamed analysis references survive project serialization")
})
