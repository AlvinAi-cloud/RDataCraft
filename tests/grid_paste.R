check(errors(pc_paste_cells(survival, "2\t1\tA\t9", 1, 1, "survival")), "survival paste cannot create a fourth column")

shiny::testServer(app, {
  # Explicit fixture: production startup is intentionally empty.
  raw(pc_example("column")$table);sheet_name("Treatment groups");project_name("Example study");document_open(TRUE)
  do.call(session$setInputs, pc_defaults()); session$flushReact()
  send_paste <- function(text, row = 1, column = 1, headers = FALSE, identity = grid_identity()) {
    session$setInputs(grid_paste = c(identity, list(text = text, row = row, column = column, headers = headers, nonce = runif(1))))
    session$flushReact()
  }
  before <- raw(); old <- grid_identity()
  send_paste("100\t200\n300\t400", 2, 1)
  check(raw()[2,1] == "100" && raw()[3,2] == "400" && raw()[1,1] == before[1,1], "grid server applies an anchored block atomically")
  check(length(data_history()$D1$undo) == 1 && tail(data_history()$D1$undo, 1)[[1]]$label == "paste cells", "a whole block is one undo action")
  pasted <- raw(); send_paste("900", identity = old)
  check(identical(raw(), pasted) && length(data_history()$D1$undo) == 1, "stale table token rejects a delayed clipboard block")
  send_paste("900", identity = list(sheet = "D99", token = grid_identity()$token))
  check(identical(raw(), pasted), "a block from another worksheet cannot change the active table")
  send_paste("1\tinvalid")
  check(identical(raw(), pasted) && length(data_history()$D1$undo) == 1, "rejected clipboard data leaves observations and history unchanged")
  session$setInputs(undo_data = 1); session$flushReact()
  check(identical(raw(), before), "one undo restores every overwritten cell")
  session$setInputs(redo_data = 1); session$flushReact()
  check(identical(raw(), pasted), "one redo reapplies the complete block")
  send_paste("Vehicle\tDrug\n10\t20", headers = TRUE)
  check(identical(names(raw())[1:2], c("Vehicle", "Drug")) && raw()[1,1] == "10", "header mode reaches the server from grid payload")
  session$setInputs(undo_data = 2); session$flushReact()
  check(identical(raw(), pasted), "undo restores renamed headers with their previous observations")
})
cat(checks, "direct-grid-paste checks passed.\n")
