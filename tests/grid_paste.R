checks <- 0L
check <- function(ok, label) {if (!isTRUE(ok)) stop("FAIL: ", label, call. = FALSE); checks <<- checks + 1L; cat("PASS:", label, "\n")}
errors <- function(expr) inherits(tryCatch(force(expr), error = identity), "error")
base <- pc_check_table(data.frame(A = 1:3, B = 4:6))
p <- pc_paste_cells(base, "10\t20\r\n30\t40\r\n", 2, 1, "column")
check(identical(unname(as.matrix(p[2:3, ])), matrix(c("10", "30", "20", "40"), 2)), "CRLF block fills the selected rectangle")
check(identical(p[1, ], base[1, ]) && identical(names(p), names(base)), "values paste preserves headers and cells outside the block")
p <- pc_paste_cells(base, "7\t8\t9\n10\t11\t12", 3, 2, "column")
check(nrow(p) == 4 && ncol(p) == 4 && p[4,4] == "12", "paste expands both dimensions")
check(is.na(p[4,1]) && is.na(p[1,4]), "expansion leaves unobserved numeric cells missing")
check(p[3,2] == "7", "first copied numeric row remains data")
p <- pc_paste_cells(base, "7\t\n\t0\n", 1, 1, "column")
check(is.na(p[1,2]) && is.na(p[2,1]) && p[2,2] == "0", "blank clipboard cells differ from observed zeros")
p <- pc_paste_cells(base, "\n", 2, 1, "column")
check(is.na(p[2,1]) && p[1,1] == "1", "empty single cell clears its target")
check(identical(as.vector(pc_clipboard_cells("1\n\n3\n")), c("1", NA_character_, "3")), "single-column blocks retain blank interior rows")
check(nrow(pc_clipboard_cells("\n\n")) == 2, "all-blank rows retain their copied extent")
p <- pc_paste_cells(base, "Vehicle\tDose\n7\t8\n9\t10", 1, 1, "column", TRUE)
check(identical(names(p), c("Vehicle", "Dose")) && p[1,1] == "7" && p[3,1] == "3", "explicit header mode renames destination columns without clearing other rows")
p <- pc_paste_cells(base, "Dose\tHigh\n7\t8", 2, 2, "column", TRUE)
check(identical(names(p), c("A", "Dose", "High")) && p[2,3] == "8", "header paste works at a column offset and adds columns")
check(errors(pc_paste_cells(base, "A\tA\n1\t2", 1, 1, "column", TRUE)), "duplicate copied headers are rejected")
check(errors(pc_paste_cells(base, "A\n1", 1, 2, "column", TRUE)), "copied headers cannot collide with untouched columns")
check(errors(pc_paste_cells(base, "Name", 1, 1, "column", TRUE)), "headers alone cannot silently erase data")
check(errors(pc_paste_cells(base, "1\t2\n3", 1, 1, "column")), "ragged clipboard blocks are rejected")
check(errors(pc_clipboard_cells('"unclosed')), "unterminated quoted clipboard text is rejected")
check(errors(pc_paste_cells(base, "1\tbad", 1, 1, "column")), "mixed valid and invalid numeric cells reject the entire block")
check(errors(pc_paste_cells(base, "Inf", 1, 1, "column")), "nonfinite numbers are rejected")
check(errors(pc_paste_cells(base, "1", 1.5, 1, "column")) && errors(pc_paste_cells(base, "1", 0, 1, "column")), "invalid anchors cannot be rounded or shifted")
check(errors(pc_paste_cells(base, "1", 4, 1, "column")), "anchor must be an existing cell")
check(errors(pc_paste_cells(base, paste(rep("1", 51), collapse = "\t"), 1, 1, "column")), "paste respects the 50-column limit")
check(errors(pc_paste_cells(base, paste(rep("1", 10000), collapse = "\n"), 2, 1, "column")), "paste respects the 10000-row limit including its offset")
check(errors(pc_clipboard_cells(paste(rep("a", 5000001), collapse = ""))), "clipboard payload size is bounded")
xy <- pc_blank("xy")
