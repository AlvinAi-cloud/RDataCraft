app<-source("app.R")$value;checks<-0L
check<-function(ok,label) {if(!isTRUE(ok)) stop("FAIL: ",label,call.=FALSE);checks<<-checks+1L;cat("PASS:",label,"\n")}
errors<-function(expr) inherits(tryCatch(force(expr),error=identity),"error")
tab<-pc_example("column")$table;s<-pc_defaults()
changed<-pc_graph_edit(tab,s,list(title='A "quoted" title & α \\ path',text_color="#123456",axis_title_size=18,point_shape=17))
check(changed$axis_title_size==18 && changed$title!=s$title,"graph edits validate text and formatting together")
p<-pc_plot(pc_normalize(tab),changed)
check(p$theme$axis.title$size==18 && p$theme$plot.title$colour=="#123456","text and axis formatting reach the rendered graph")
svg<-pc_graph_svg(p,changed,list(sheet="D1",view="V1",token="test"))
check(grepl("rdatacraft-interaction",svg,fixed=TRUE) && grepl("&amp;",svg,fixed=TRUE),"preview SVG carries escaped interaction metadata")
check(!grepl("rdatacraft-interaction",pc_graph_svg(p,changed),fixed=TRUE),"export SVG contains no interactive editing metadata")
check(errors(pc_graph_edit(tab,s,list(axis_color="red<script>"))),"invalid colors cannot enter graph settings")
check(errors(pc_graph_edit(tab,s,list(y_min="10",y_max="1"))),"invalid axis ranges reject the entire formatting change")
check(errors(pc_graph_edit(tab,s,list(method="paired"))),"formatting cannot change the statistical method")
check(errors(pc_graph_edit(tab,s,list(width=0))),"invalid canvas size is rejected")
check(errors(pc_graph_edit(tab,s,list(point_shape=1.5))),"symbol identifiers must be whole numbers")
v<-list(V1=pc_view(s),V2=pc_view(changed,"Alternative"));book<-list(D1=pc_sheet(tab,changed,"Experiment",v,"V2"));layout<-pc_layout_defaults();layout$selected<-c("D1:V1","D1:V2")
r<-pc_delete_view(book,"D1","V2",layout)
check(length(r$book$D1$views)==1 && r$book$D1$active_view=="V1","deleting the active view selects a remaining view")
check(identical(r$book$D1$data_tsv,book$D1$data_tsv) && identical(r$book$D1$settings,s),"view deletion preserves observations and restores remaining settings")
check(identical(r$layout$selected,"D1:V1"),"deleted graph is removed from layout selections")
check(errors(pc_delete_view(r$book,"D1","V1",r$layout)),"the final linked view cannot be deleted")
check(errors(pc_delete_view(book,"D1","V99",layout)),"stale view references are rejected")
payload<-pc_vector_payload(p,changed)
check(rawToChar(head(jsonlite::base64_dec(payload$pdf),4))=="%PDF" && grepl("<svg",payload$svg,fixed=TRUE),"vector payload includes real PDF and SVG")
check(!grepl("<image",payload$svg,fixed=TRUE),"ordinary vector graph does not embed a raster screenshot")
shiny::testServer(app,{
  # Explicit fixture: production startup is intentionally empty.
  raw(pc_example("column")$table);sheet_name("Treatment groups");project_name("Example study");document_open(TRUE)
  do.call(session$setInputs,pc_defaults());session$flushReact()
  ack<-function(){target<-restoring_settings();if(!is.null(target)) do.call(session$setInputs,target);session$flushReact()}
  before<-raw();context<-graph_context()
  session$setInputs(graph_edit=c(context,list(changes=list(title="Clicked title",axis_color="#123456",axis_title_size=17),nonce=1)));session$flushReact();ack()
  check(settings()$title=="Clicked title" && settings()$axis_title_size==17,"direct graph edits survive settings acknowledgement")
  check(identical(raw(),before),"direct graph editing preserves source observations")
  session$setInputs(graph_edit=c(context,list(changes=list(title="Stale edit"),nonce=2)));session$flushReact();ack()
  check(settings()$title=="Clicked title","stale preview token cannot edit a newer graph")
  session$setInputs(new_view_name="Alternative",confirm_new_view=1);session$flushReact();ack()
  session$setInputs(layout_views=c("D1:V1","D1:V2"));session$flushReact()
  session$setInputs(delete_view=1);session$flushReact();session$setInputs(confirm_delete_view=1);session$flushReact();ack()
  check(active_view()=="V1" && length(view_book())==1,"server deletes alternative views and restores the surviving graph")
  check(identical(layout_settings()$selected,"D1:V1"),"layout references are valid before client selection acknowledgement")
  file<-"artifacts/tests/graph-edits.rdatacraft";pc_write_project(snapshot(),file);saved<-pc_load_project(file)
  check(saved$settings$axis_color=="#123456" && saved$settings$axis_title_size==17 && length(saved$worksheets$D1$views)==1,"graph formatting and view deletion persist on save/reopen")
})
